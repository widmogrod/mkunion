package gen

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const vehicleSource = `package vehicle

//go:tag mkunion:"Vehicle"
type (
	Car struct {
		Brand string
	}
	Plane struct {
		Engines int
	}
)
`

// writeVehicleModule creates a small Go module with one union type and
// returns the path of its source file.
func writeVehicleModule(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()

	goMod := `module example.com/vehicle

go 1.21
`
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte(goMod), 0644))

	sourcePath := filepath.Join(dir, "vehicle.go")
	require.NoError(t, os.WriteFile(sourcePath, []byte(vehicleSource), 0644))

	return sourcePath
}

func TestGenerate(t *testing.T) {
	t.Run("generates_union_shape_and_type_registry", func(t *testing.T) {
		sourcePath := writeVehicleModule(t)
		dir := filepath.Dir(sourcePath)

		savedFiles, err := Generate([]string{sourcePath}, true)
		require.NoError(t, err)

		expected := []string{
			filepath.Join(dir, "vehicle_union_gen.go"),
			filepath.Join(dir, "vehicle_shape_gen.go"),
			filepath.Join(dir, "types_reg_gen.go"),
		}
		assert.ElementsMatch(t, expected, savedFiles)

		unionContent, err := os.ReadFile(filepath.Join(dir, "vehicle_union_gen.go"))
		require.NoError(t, err)
		assert.Contains(t, string(unionContent), "// Code generated by mkunion. DO NOT EDIT.")
		assert.Contains(t, string(unionContent), "type Vehicle interface")

		shapeContent, err := os.ReadFile(filepath.Join(dir, "vehicle_shape_gen.go"))
		require.NoError(t, err)
		assert.Contains(t, string(shapeContent), "VehicleShape()")

		registryContent, err := os.ReadFile(filepath.Join(dir, "types_reg_gen.go"))
		require.NoError(t, err)
		assert.Contains(t, string(registryContent), `shared.TypeRegistryStore[Car]("example.com/vehicle.Car")`)
		assert.Contains(t, string(registryContent), `shared.TypeRegistryStore[Plane]("example.com/vehicle.Plane")`)
	})

	t.Run("type_registry_disabled_skips_registry_file", func(t *testing.T) {
		sourcePath := writeVehicleModule(t)
		dir := filepath.Dir(sourcePath)

		savedFiles, err := Generate([]string{sourcePath}, false)
		require.NoError(t, err)

		for _, file := range savedFiles {
			assert.NotEqual(t, "types_reg_gen.go", filepath.Base(file))
		}
		_, err = os.Stat(filepath.Join(dir, "types_reg_gen.go"))
		assert.True(t, os.IsNotExist(err))
	})

	t.Run("file_without_unions_generates_nothing", func(t *testing.T) {
		dir := t.TempDir()
		goMod := "module example.com/empty\n\ngo 1.21\n"
		require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte(goMod), 0644))

		sourcePath := filepath.Join(dir, "empty.go")
		source := "package empty\n\nfunc Hello() string { return \"hi\" }\n"
		require.NoError(t, os.WriteFile(sourcePath, []byte(source), 0644))

		savedFiles, err := Generate([]string{sourcePath}, true)
		require.NoError(t, err)
		assert.Empty(t, savedFiles)
	})

	t.Run("missing_source_file_returns_error", func(t *testing.T) {
		_, err := Generate([]string{"/path/that/does/not/exist.go"}, false)
		assert.Error(t, err)
	})
}
