package gen

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const vehicleSource = `package vehicle

//go:tag mkunion:"Vehicle"
type (
	Car struct {
		Brand string
	}
	Plane struct {
		Engines int
	}
)
`

// writeVehicleModule creates a small Go module with one union type and
// returns the path of its source file.
func writeVehicleModule(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()

	goMod := `module example.com/vehicle

go 1.21
`
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte(goMod), 0644))

	sourcePath := filepath.Join(dir, "vehicle.go")
	require.NoError(t, os.WriteFile(sourcePath, []byte(vehicleSource), 0644))

	return sourcePath
}

func TestGenerate(t *testing.T) {
	t.Run("generates_union_shape_and_type_registry", func(t *testing.T) {
		sourcePath := writeVehicleModule(t)
		dir := filepath.Dir(sourcePath)

		savedFiles, err := Generate([]string{sourcePath}, true)
		require.NoError(t, err)

		expected := []string{
			filepath.Join(dir, "vehicle_union_gen.go"),
			filepath.Join(dir, "vehicle_shape_gen.go"),
			filepath.Join(dir, "types_reg_gen.go"),
		}
		assert.ElementsMatch(t, expected, savedFiles)

		unionContent, err := os.ReadFile(filepath.Join(dir, "vehicle_union_gen.go"))
		require.NoError(t, err)
		assert.Contains(t, string(unionContent), "// Code generated by mkunion. DO NOT EDIT.")
		assert.Contains(t, string(unionContent), "type Vehicle interface")

		shapeContent, err := os.ReadFile(filepath.Join(dir, "vehicle_shape_gen.go"))
		require.NoError(t, err)
		assert.Contains(t, string(shapeContent), "VehicleShape()")

		registryContent, err := os.ReadFile(filepath.Join(dir, "types_reg_gen.go"))
		require.NoError(t, err)
		assert.Contains(t, string(registryContent), `shared.TypeRegistryStore[Car]("example.com/vehicle.Car")`)
		assert.Contains(t, string(registryContent), `shared.TypeRegistryStore[Plane]("example.com/vehicle.Plane")`)
	})

	t.Run("type_registry_disabled_skips_registry_file", func(t *testing.T) {
		sourcePath := writeVehicleModule(t)
		dir := filepath.Dir(sourcePath)

		savedFiles, err := Generate([]string{sourcePath}, false)
		require.NoError(t, err)

		for _, file := range savedFiles {
			assert.NotEqual(t, "types_reg_gen.go", filepath.Base(file))
		}
		_, err = os.Stat(filepath.Join(dir, "types_reg_gen.go"))
		assert.True(t, os.IsNotExist(err))
	})

	t.Run("file_without_unions_generates_nothing", func(t *testing.T) {
		dir := t.TempDir()
		goMod := "module example.com/empty\n\ngo 1.21\n"
		require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte(goMod), 0644))

		sourcePath := filepath.Join(dir, "empty.go")
		source := "package empty\n\nfunc Hello() string { return \"hi\" }\n"
		require.NoError(t, os.WriteFile(sourcePath, []byte(source), 0644))

		savedFiles, err := Generate([]string{sourcePath}, true)
		require.NoError(t, err)
		assert.Empty(t, savedFiles)
	})

	t.Run("missing_source_file_returns_error", func(t *testing.T) {
		_, err := Generate([]string{"/path/that/does/not/exist.go"}, false)
		assert.Error(t, err)
	})

	t.Run("struct_holding_union_gets_serde", func(t *testing.T) {
		sourcePath := writeVehicleModule(t)
		dir := filepath.Dir(sourcePath)

		source := vehicleSource + `
// Garage has no serde tag; it holds the union, so serde is generated for it.
type Garage struct {
	Parked []Vehicle
}

// Fleet is a named list of the union; it gets serde too.
type Fleet []Vehicle

// Plain holds no union: encoding/json is enough.
type Plain struct {
	Name string
}

// Custom holds the union but opts out of generated serde.
//
//go:tag serde:"-"
type Custom struct {
	One Vehicle
}
`
		require.NoError(t, os.WriteFile(sourcePath, []byte(source), 0644))

		savedFiles, err := Generate([]string{sourcePath}, true)
		require.NoError(t, err)

		serdePath := filepath.Join(dir, "vehicle_serde_gen.go")
		assert.Contains(t, savedFiles, serdePath)

		content, err := os.ReadFile(serdePath)
		require.NoError(t, err)
		serde := string(content)
		assert.Contains(t, serde, "// Garage holds a union: serde generated so encoding/json keeps $type.")
		assert.Contains(t, serde, "func (r *Garage) MarshalJSON")
		assert.Contains(t, serde, "func (r *Fleet) MarshalJSON")
		assert.NotContains(t, serde, "func (r *Plain) MarshalJSON")
		assert.NotContains(t, serde, "func (r *Custom) MarshalJSON")
	})
}

// TestGenerate_answerUnionInSiblingFile is the api layout: the request union
// in query.go names its answer union with answers=, and that union lives in
// answer.go of the same package. DispatchX and NewXClient are generated for
// query.go whether answer.go is given to Generate or not.
func TestGenerate_answerUnionInSiblingFile(t *testing.T) {
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/todo\n\ngo 1.21\n"), 0644))
	query := filepath.Join(dir, "query.go")
	require.NoError(t, os.WriteFile(query, []byte(`package task

import "github.com/widmogrod/mkunion/f"

//go:tag mkunion:"TaskQuery,answers=TaskAnswer"
type (
	GetTask struct {
		f.Returns[*Task]
		ID string
	}
)
`), 0644))
	answer := filepath.Join(dir, "answer.go")
	require.NoError(t, os.WriteFile(answer, []byte(`package task

//go:tag mkunion:"TaskAnswer"
type (
	Task  struct{ ID string }
	Error struct{ Code string }
)
`), 0644))

	for name, paths := range map[string][]string{
		"both files":     {query, answer},
		"query.go alone": {query},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := Generate(paths, false)
			require.NoError(t, err)
			content, err := os.ReadFile(filepath.Join(dir, "query_union_gen.go"))
			require.NoError(t, err)
			assert.Contains(t, string(content), "func DispatchTaskQuery(ctx context.Context, h TaskQueryHandler, op TaskQuery) (TaskAnswer, error) {")
			assert.Contains(t, string(content), "func NewTaskQueryClient(send func(ctx context.Context, op TaskQuery) (TaskAnswer, error)) TaskQueryHandler {")
		})
	}

	t.Run("a missing answer union names the package", func(t *testing.T) {
		require.NoError(t, os.Remove(answer))
		_, err := Generate([]string{query}, false)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "answers=TaskAnswer names no union in package task")
	})
}
