package gen

import (
	"context"
	"path/filepath"
	"strings"
	"sync"
	"time"

	"github.com/fsnotify/fsnotify"
	log "github.com/sirupsen/logrus"
	"github.com/widmogrod/mkunion/x/shape"
)

// WatchOptions controls how Watch regenerates code on file changes.
type WatchOptions struct {
	// TypeRegistry regenerates types_reg_gen.go files when set.
	TypeRegistry bool
	// RunGoGenerate runs 'go generate ./...' after regeneration when set.
	RunGoGenerate bool
}

// Watch watches the given directories for .go file changes and regenerates
// mkunion output until ctx is cancelled.
func Watch(ctx context.Context, paths []string, opts WatchOptions) error {
	watcher, err := fsnotify.NewWatcher()
	if err != nil {
		return err
	}
	defer watcher.Close()

	w := &watchLoop{
		watcher: watcher,
		opts:    opts,
	}

	done := make(chan bool)
	go func() {
		defer close(done)
		w.run(ctx)
	}()

	for _, path := range paths {
		err = watcher.Add(path)
		if err != nil {
			return err
		}
	}

	<-done
	return nil
}

// watchLoop tracks in-flight file events so that files written by the
// generator itself do not re-trigger generation (which would loop forever).
type watchLoop struct {
	watcher *fsnotify.Watcher
	opts    WatchOptions

	justGenerated sync.Map
	justChanged   sync.Map
	justRemoved   sync.Map
}

func (w *watchLoop) run(ctx context.Context) {
	for {
		select {
		case <-ctx.Done():
			return

		case event, ok := <-w.watcher.Events:
			if !ok {
				return
			}
			w.handleEvent(event)

		case err, ok := <-w.watcher.Errors:
			if !ok {
				return
			}
			log.Errorf("Error: %s", err)

		case <-time.After(250 * time.Millisecond):
			// no new events for a while; process what accumulated
			w.processRemoved()
			w.processChanged()
		}
	}
}

func (w *watchLoop) handleEvent(event fsnotify.Event) {
	if filepath.Ext(event.Name) != ".go" {
		return
	}

	if event.Op&fsnotify.Chmod == fsnotify.Chmod {
		return
	}

	pathName := strings.Trim(event.Name, `"`)
	if event.Op&fsnotify.Remove == fsnotify.Remove {
		w.justRemoved.Store(pathName, true)
	} else {
		w.justChanged.Store(pathName, true)
	}

	// if the file was generated by the watch process itself, forget that mark
	// after a debounce, so a later edit of the same file is picked up again
	// without causing an infinite generation loop now
	if _, ok := w.justGenerated.Load(pathName); ok {
		go func(pathName string) {
			time.Sleep(2 * time.Second)
			w.justGenerated.Delete(pathName)
		}(pathName)
	}
}

func (w *watchLoop) processRemoved() {
	deletedUnique := make(map[string]bool)
	w.justRemoved.Range(func(key, value interface{}) bool {
		pathName := key.(string)
		dir := filepath.Dir(pathName)
		if _, ok := w.justGenerated.Load(pathName); !ok {
			deletedUnique[dir] = true
		}
		w.justRemoved.Delete(key)
		return true
	})

	deleted := make([]string, 0, len(deletedUnique))
	for x := range deletedUnique {
		deleted = append(deleted, x)
	}

	if len(deleted) == 0 {
		return
	}

	shape.ResetIndex()
	savedFiles, err := quietly(func() ([]string, error) {
		return GenerateTypeRegistryForDir(deleted)
	})
	if err != nil {
		log.Warnf("failed to generate type registry for %v: %s", deleted, err)
		return
	}

	for _, x := range savedFiles {
		log.Infof("re-generated:\t%s", x)
		w.justGenerated.Store(x, true)
	}

	if len(savedFiles) > 0 {
		log.Infof("re-generated: done for deleted files")
	} else {
		log.Infof("re-generated: delete not resulted in any new files")
	}
}

func (w *watchLoop) processChanged() {
	var changedSourcePaths []string
	w.justChanged.Range(func(key, value interface{}) bool {
		pathName := key.(string)
		if _, ok := w.justGenerated.Load(pathName); !ok {
			changedSourcePaths = append(changedSourcePaths, pathName)
		}

		w.justChanged.Delete(key)
		return true
	})

	if len(changedSourcePaths) == 0 {
		return
	}

	shape.ResetIndex()
	savedFiles, err := quietly(func() ([]string, error) {
		return Generate(changedSourcePaths, w.opts.TypeRegistry)
	})

	for _, x := range savedFiles {
		log.Infof("re-generated:\t%s", x)
		w.justGenerated.Store(x, true)
	}

	if err != nil {
		log.Errorf("failed to generate: %s", err)
	}

	if len(savedFiles) == 0 {
		log.Infof("re-generated: change not resulted in any new files")
		return
	}

	log.Infof("re-generated: done for changed files")

	if w.opts.RunGoGenerate {
		dirsMap := make(map[string]bool)
		for _, file := range changedSourcePaths {
			dirsMap[filepath.Dir(file)] = true
		}

		dirs := make([]string, 0, len(dirsMap))
		for dir := range dirsMap {
			dirs = append(dirs, dir)
		}

		// Errors are already logged by RunGoGenerate
		_ = RunGoGenerate(dirs)
	}
}

// quietly runs f with logging reduced to errors, so bulk regeneration does not
// flood the watch output, and restores the previous level after.
func quietly(f func() ([]string, error)) ([]string, error) {
	prevLevel := log.GetLevel()
	log.SetLevel(log.ErrorLevel)
	defer log.SetLevel(prevLevel)
	return f()
}
