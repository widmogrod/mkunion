func TestCrapScore(t *testing.T) {
	// fully covered function: CRAP == complexity
	assert.InDelta(t, 5.0, crapScore(5, 1.0), 0.001)
	// fully uncovered function: CRAP == cc^2 + cc
	assert.InDelta(t, 30.0, crapScore(5, 0.0), 0.001)
	// half covered
	assert.InDelta(t, 5*5*0.125+5, crapScore(5, 0.5), 0.001)
}

func parseFunc(t *testing.T, src string) *ast.FuncDecl {
	t.Helper()
	file, err := parser.ParseFile(token.NewFileSet(), "src.go", "package p\n"+src, 0)
	require.NoError(t, err)
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok {
			return fn
		}
	}
	t.Fatal("no function in source")
	return nil
}

func TestComplexity(t *testing.T) {
	cases := []struct {
		name string
		src  string
		want int
	}{
		{"empty", `func f() {}`, 1},
		{"if", `func f(a bool) { if a {} }`, 2},
		{"if-and", `func f(a, b bool) { if a && b {} }`, 3},
		{"for-range", `func f(xs []int) { for range xs {} }`, 2},
		{"switch-with-default", `func f(a int) { switch a { case 1: case 2: default: } }`, 3},
		{"select", `func f(ch chan int) { select { case <-ch: default: } }`, 2},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			assert.Equal(t, c.want, complexity(parseFunc(t, c.src)))
		})
	}
}

func TestFuncName(t *testing.T) {
	assert.Equal(t, "f", funcName(parseFunc(t, `func f() {}`)))
	assert.Equal(t, "*T.m", funcName(parseFunc(t, `type T struct{}; func (t *T) m() {}`)))
	assert.Equal(t, "G.m", funcName(parseFunc(t, `type G[A any] struct{}; func (g G[A]) m() {}`)))
}

func TestIsGenerated(t *testing.T) {
	gen, err := parser.ParseFile(token.NewFileSet(), "g.go",
		"// Code generated by mkunion. DO NOT EDIT.\npackage p\n", parser.ParseComments)
	require.NoError(t, err)
	assert.True(t, isGenerated(gen))

	plain, err := parser.ParseFile(token.NewFileSet(), "p.go",
		"// just a comment\npackage p\n", parser.ParseComments)
	require.NoError(t, err)
	assert.False(t, isGenerated(plain))
}

func TestCollectStats(t *testing.T) {
	root := t.TempDir()
	writeFile := func(rel, content string) {
		require.NoError(t, os.MkdirAll(filepath.Dir(filepath.Join(root, rel)), 0755))
		require.NoError(t, os.WriteFile(filepath.Join(root, rel), []byte(content), 0644))
	}
	writeFile("lib/lib.go", `package lib

func Covered(a bool) int {
	if a {
		return 1
	}
	return 0
}

func Uncovered(a bool) int {
	if a {
		return 1
	}
	return 0
}
`)
	writeFile("lib/lib_test.go", "package lib\n")
	writeFile("lib/gen.go", "// Code generated by mkunion. DO NOT EDIT.\npackage lib\n\nfunc Gen() {}\n")
	writeFile("skipme/skip.go", "package skipme\n\nfunc Skip() {}\n")

	blocks := map[string][]cover.ProfileBlock{
		"example.com/mod/lib/lib.go": {
			{StartLine: 3, EndLine: 5, NumStmt: 1, Count: 1},
			{StartLine: 5, EndLine: 7, NumStmt: 1, Count: 1},
			{StartLine: 10, EndLine: 12, NumStmt: 1, Count: 0},
			{StartLine: 12, EndLine: 14, NumStmt: 1, Count: 0},
		},
	}

	stats, err := collectStats(root, "example.com/mod", blocks, false, []string{"skipme"})
	require.NoError(t, err)

	byKey := map[string]funcStat{}
	for _, s := range stats {
		byKey[s.File+":"+s.Name] = s
	}
	require.Len(t, byKey, 2, "test, generated and skipped files must be excluded")

	covered := byKey["lib/lib.go:Covered"]
	assert.Equal(t, 2, covered.Complexity)
	assert.InDelta(t, 1.0, covered.Coverage, 0.001)
	assert.InDelta(t, 2.0, covered.Crap, 0.001)

	uncovered := byKey["lib/lib.go:Uncovered"]
	assert.Equal(t, 2, uncovered.Complexity)
	assert.InDelta(t, 0.0, uncovered.Coverage, 0.001)
	assert.InDelta(t, 6.0, uncovered.Crap, 0.001)
}
