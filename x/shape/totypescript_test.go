// The TypeScript the exporter writes for testasset/type_api.go is kept under
// testasset/typescript and compared byte for byte, like the Swift golden. Set
// UPDATE_GOLDEN=1 to rewrite it.
func TestTypeScriptExport(t *testing.T) {
	inferred, err := InferFromFile("testasset/type_api.go")
	require.NoError(t, err)

	r := NewTypeScriptRenderer()
	for _, x := range inferred.RetrieveShapes() {
		r.AddShape(x)
	}
	files, err := r.Render()
	require.NoError(t, err)

	assert.ElementsMatch(t, []string{"testasset.ts", "mkunion.ts"}, keys(files))

	for name, content := range files {
		golden := filepath.Join("testasset", "typescript", name)
		if os.Getenv("UPDATE_GOLDEN") == "1" {
			require.NoError(t, os.MkdirAll(filepath.Dir(golden), 0755))
			require.NoError(t, os.WriteFile(golden, []byte(content), 0644))
		}
		want, err := os.ReadFile(golden)
		require.NoError(t, err, "run with UPDATE_GOLDEN=1 to write %s", golden)
		assert.Equal(t, string(want), content, name)
	}
}

// The example union exercises what type_api.go does not: aliases of every
// primitive, a map and a list of the union, generics, a second package, and
// fields with no json tag, which keep their Go names.
func TestTypeScriptSchemaGeneration(t *testing.T) {
	inferred, err := InferFromFile("testasset/type_example.go")
	require.NoError(t, err)

	tsr := NewTypeScriptRenderer()
	tsr.AddShape(inferred.RetrieveUnion("Example"))
	tsr.AddShape(inferred.RetrieveStruct("ListOf2"))
	tsr.AddShape(&StructLike{
		Name:          "SomeStruct",
		PkgName:       "test",
		PkgImportName: "go.import.test",
		Fields: []*FieldLike{
			{Name: "Example", Type: &RefName{Name: "Example", PkgName: "testasset", PkgImportName: "github.com/widmogrod/mkunion/x/shape/testasset"}},
		},
	})

	files, err := tsr.Render()
	require.NoError(t, err)
	assert.ElementsMatch(t, []string{"testasset.ts", "test.ts", "mkunion.ts"}, keys(files), "one file per Go package, plus the prelude; no f.ts, no time.ts")

	expected := `// Code generated by mkunion. DO NOT EDIT.
/* eslint-disable */

import type * as mkunion from "./mkunion";

/** Go package testasset (github.com/widmogrod/mkunion/x/shape/testasset). */

/** Example is a union: one object per variant, on the wire as {"$type": "testasset.A", "testasset.A": {...}}. Go writes both keys. */
export type Example =
  | { "$type": "testasset.A"; "testasset.A": A }
  | { "$type": "testasset.B"; "testasset.B": B }
  | { "$type": "testasset.C"; "testasset.C": C }
  | { "$type": "testasset.D"; "testasset.D": D }
  | { "$type": "testasset.E"; "testasset.E": E }
  | { "$type": "testasset.F"; "testasset.F": F }
  | { "$type": "testasset.H"; "testasset.H": H }
  | { "$type": "testasset.I"; "testasset.I": I }
  | { "$type": "testasset.J"; "testasset.J": J }
  | { "$type": "testasset.K"; "testasset.K": K }
  | { "$type": "testasset.L"; "testasset.L": L }
  | { "$type": "testasset.M"; "testasset.M": M }
  | { "$type": "testasset.N"; "testasset.N": N }
  | { "$type": "testasset.O"; "testasset.O": O }
  | { "$type": "testasset.P"; "testasset.P": P };

export type A = {
  /** Name of the person */
  name: string;
};

export type B = {
  age: number;
  A: A | null;
  T: mkunion.RFC3339 | null;
};

export type C = string;

export type D = number;

export type E = number;

export type F = boolean;

export type H = Record<string, Example | null>;

export type I = (Example | null)[];

export type J = string[];

export type K = A;

export type L = List;

export type M = List;

export type N = number;

export type O = ListOf<number>;

export type P = ListOf2<ListOf<unknown>, ListOf2<number, number | null> | null>;

/** List has no fields; Go writes {}. */
export type List = Record<string, never>;

/** ListOf has no fields; Go writes {}. */
export type ListOf<T> = Record<string, never>;

export type ListOf2<T1, T2> = {
  Data: T1;
  list_of: ListOf<T1>;
};
`
	assert.Equal(t, expected, files["testasset.ts"])

	assert.Equal(t, `// Code generated by mkunion. DO NOT EDIT.
/* eslint-disable */

import type * as testasset from "./testasset";

/** Go package test (go.import.test). */

export type SomeStruct = {
  Example: testasset.Example | null;
};
`, files["test.ts"], "another package is imported as a namespace, and a union field may be null")
}

// What a field becomes: json names, omitempty, and where Go may write null,
// which depends on the encoder: Row holds a union so the generated serde
// writes it, as it does Steps; Plain and Names are left to encoding/json.
func TestTypeScriptFields(t *testing.T) {
	inferred, err := InferFromFileWithContentBody(`package demo

import "time"

//go:tag mkunion:"State"
type (
	On  struct{}
	Off struct{}
)

type Record struct{ Keep string }

type Plain struct {
	List  []string       `+"`json:\"list\"`"+`
	Dict  map[string]int `+"`json:\"dict\"`"+`
	Bytes []byte         `+"`json:\"bytes\"`"+`
	Names Names          `+"`json:\"names\"`"+`
}

type Names []string

type Steps []State

type Row struct {
	Plain     string
	Tagged    string            `+"`json:\"tagged\"`"+`
	Hidden    string            `+"`json:\"-\"`"+`
	Dashed    string            `+"`json:\"with-dash\"`"+`
	Opt       string            `+"`json:\"opt,omitempty\"`"+`
	OptPtr    *string           `+"`json:\"optPtr,omitempty\"`"+`
	OptList   []string          `+"`json:\"optList,omitempty\"`"+`
	Ptr       *int              `+"`json:\"ptr\"`"+`
	List      []int             `+"`json:\"list\"`"+`
	Array     [2]int            `+"`json:\"array\"`"+`
	Bytes     []byte            `+"`json:\"bytes\"`"+`
	Dict      map[int]bool      `+"`json:\"dict\"`"+`
	Union     State             `+"`json:\"union\"`"+`
	When      time.Time         `+"`json:\"when\"`"+`
	Took      time.Duration     `+"`json:\"took\"`"+`
	Anything  any               `+"`json:\"anything\"`"+`
	Rec       Record            `+"`json:\"rec\"`"+`
	Zero      int               `+"`json:\"zero,omitzero\"`"+`
	Steps     Steps             `+"`json:\"steps\"`"+`
}
`, "example.com/demo")
	require.NoError(t, err)

	r := NewTypeScriptRenderer()
	for _, x := range inferred.RetrieveShapes() {
		r.AddShape(x)
	}
	files, err := r.Render()
	require.NoError(t, err)

	assert.Contains(t, files["demo.ts"], `export type Row = {
  Plain: string;
  tagged: string;
  "with-dash": string;
  opt?: string;
  optPtr?: string;
  optList?: string[];
  ptr: number | null;
  list: number[];
  array: number[];
  bytes: mkunion.Base64 | null;
  dict: Record<string, boolean>;
  union: State | null;
  when: mkunion.RFC3339;
  took: number;
  anything: unknown;
  rec: Record_;
  zero?: number;
  steps: Steps;
};
`)
	assert.Contains(t, files["demo.ts"], `export type Plain = {
  list: string[] | null;
  dict: Record<string, number> | null;
  bytes: mkunion.Base64 | null;
  names: Names | null;
};
`, "encoding/json writes null for a nil slice or map, and for a nil named slice without serde of its own")
	assert.Contains(t, files["demo.ts"], "export type Names = string[];\n", "the alias itself is the type; its null belongs to the field")
	assert.Contains(t, files["demo.ts"], "export type Steps = (State | null)[];\n")
	assert.Contains(t, files["demo.ts"], "export type Record_ = {", "a Go type named Record steps aside for the global")
	assert.Contains(t, files["demo.ts"], "import type * as mkunion", "only types are used from the prelude")
	assert.NotContains(t, files["demo.ts"], "send", "no f.Returns, no send")
}

// Shapes the exporter does not support stop the export with an error that
// names them, instead of writing TypeScript that does not compile.
func TestTypeScriptExportRefusesWhatItCannotWrite(t *testing.T) {
	inline := &StructLike{
		Name: "Outer", PkgName: "demo", PkgImportName: "example.com/demo",
		Fields: []*FieldLike{{Name: "Inner", Type: &StructLike{
			Fields: []*FieldLike{{Name: "N", Type: &PrimitiveLike{Kind: &NumberLike{Kind: &Int{}}}}},
		}}},
	}
	empty := &UnionLike{Name: "Nothing", PkgName: "demo", PkgImportName: "example.com/demo"}
	taken := &UnionLike{Name: "Query", PkgName: "demo", PkgImportName: "example.com/demo", Variant: []Shape{
		&StructLike{Name: "Ping", PkgName: "demo", PkgImportName: "example.com/demo", Fields: []*FieldLike{
			{Name: "Returns", Type: &RefName{Name: "Returns", PkgName: "f", PkgImportName: returnsPkgImportName, Indexed: []Shape{&PrimitiveLike{Kind: &StringLike{}}}}},
		}},
	}}
	clash := &StructLike{Name: "QueryAnswer", PkgName: "demo", PkgImportName: "example.com/demo"}

	r := NewTypeScriptRenderer()
	for _, x := range []Shape{inline, empty, taken, clash} {
		r.AddShape(x)
	}
	_, err := r.Render()
	require.Error(t, err)
	for _, want := range []string{
		"demo.Outer.Inner is an inline struct",
		"demo.Nothing has no variants",
		"demo.QueryAnswer is a type and the name Query needs",
	} {
		assert.Contains(t, err.Error(), want)
	}
}

// An answer that is not a variant of the union the other answers belong to
// cannot come back on the wire, so the export says so instead of dropping
// send for every operation.
func TestTypeScriptExportRefusesAnAnswerOutsideTheAnswerUnion(t *testing.T) {
	inferred, err := InferFromFileWithContentBody(`package demo

import "github.com/widmogrod/mkunion/f"

//go:tag mkunion:"Request"
type (
	GetInfo   struct{ f.Returns[*Info] }
	CancelJob struct {
		f.Returns[*Job]
		ID string `+"`json:\"id\"`"+`
	}
)

//go:tag mkunion:"Response"
type (
	Info struct{ Name string `+"`json:\"name\"`"+` }
)

type Job struct{ ID string `+"`json:\"id\"`"+` }
`, "example.com/demo")
	require.NoError(t, err)

	r := NewTypeScriptRenderer()
	for _, x := range inferred.RetrieveShapes() {
		r.AddShape(x)
	}
	files, err := r.Render()
	require.Error(t, err)
	assert.Contains(t, err.Error(), "demo.CancelJob answers with demo.Job, which is not a variant of demo.Response like the other answers of demo.Request")
	assert.NotContains(t, files["demo.ts"], "export function send", "send is not written half-right")
	assert.Contains(t, files["demo.ts"], `"demo.CancelJob": Job;`, "the answer table is still there")
}

// Two Go packages with the same base name, or one named like the prelude,
// would land in the same file.
func TestTypeScriptExportRefusesFileNameClash(t *testing.T) {
	r := NewTypeScriptRenderer()
	r.AddShape(&StructLike{Name: "A", PkgName: "api", PkgImportName: "example.com/one/api"})
	r.AddShape(&StructLike{Name: "B", PkgName: "api", PkgImportName: "example.com/two/api"})
	r.AddShape(&StructLike{Name: "C", PkgName: "mkunion", PkgImportName: "example.com/mkunion"})
	_, err := r.Render()
	require.Error(t, err)
	assert.Contains(t, err.Error(), "both render as api.ts")
	assert.Contains(t, err.Error(), "the mkunion prelude and example.com/mkunion both render as mkunion.ts")
}

func TestTypeScriptNames(t *testing.T) {
	assert.Equal(t, "Record_", tsTypeName("Record"))
	assert.Equal(t, "Promise_", tsTypeName("Promise"))
	assert.Equal(t, "Error", tsTypeName("Error"), "a module is a namespace; api.Error is fine")
	assert.Equal(t, "query", tsPropertyName("query"))
	assert.Equal(t, "$type", tsPropertyName("$type"))
	assert.Equal(t, `"with-dash"`, tsPropertyName("with-dash"))
	assert.Equal(t, `"1st"`, tsPropertyName("1st"))
}
